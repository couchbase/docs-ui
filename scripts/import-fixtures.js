'use strict'

// Refreshes preview-src/fixtures/ from the content repos listed in
// preview-src/fixtures/manifest.yml (see that file for the format).
// Reads via `git show origin/<ref>:<path>` so nothing is checked out; run
// `git fetch` in the clones first if you want newer content.

const { execFileSync } = require('child_process')
const crypto = require('crypto')
const fs = require('fs')
const path = require('path')
const yaml = require('js-yaml')

const root = path.resolve(__dirname, '..')
const fixturesDir = path.join(root, 'preview-src', 'fixtures')
const reposDir = path.resolve(process.env.CONTENT_REPOS_DIR || path.join(root, '..'))
const manifest = yaml.safeLoad(fs.readFileSync(path.join(fixturesDir, 'manifest.yml'), 'utf8'))

const git = (repo, args) =>
  execFileSync('git', ['-C', path.join(reposDir, repo), ...args], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })

function show (repo, ref, file) {
  return git(repo, ['show', `origin/${ref}:${file}`])
}

function truncateAtHeading (lines, maxLines) {
  if (lines.length <= maxLines) return lines
  for (let i = maxLines; i > maxLines / 2; i--) if (/^={2,4} \S/.test(lines[i])) return lines.slice(0, i)
  return lines.slice(0, maxLines)
}

function transform (page, source) {
  let lines = source.replace(/\r\n/g, '\n').split('\n')
  lines = truncateAtHeading(lines, page.maxLines || Infinity)
  const out = []
  let titleSeen = false
  for (const line of lines) {
    const include = line.match(/^include::([^[]+)\[.*\]\s*$/)
    if (include) {
      const target = include[1]
      if (page.inline && page.inline[target]) {
        out.push(show(page.repo, page.ref, page.inline[target]).replace(/\n$/, ''))
      } else {
        out.push(`// [fixture] omitted: ${line}`)
      }
      continue
    }
    out.push(line)
    if (!titleSeen && /^= \S/.test(line)) {
      titleSeen = true
      out.push(...(page.attrs || []))
    }
  }
  return out.join('\n').replace(/\n*$/, '\n')
}

const lock = {}
const index = []
for (const page of manifest.pages) {
  const sha = git(page.repo, ['rev-parse', `origin/${page.ref}`]).trim()
  const header =
    `// FIXTURE ${page.id}: ${page.repo}@${page.ref} (${sha.slice(0, 8)}) ${page.path}\n` +
    '// Imported, trimmed and sanitised by scripts/import-fixtures.js. Do not edit by hand.\n'
  const body = transform(page, show(page.repo, page.ref, page.path))
  const dest = path.join(fixturesDir, page.dest)
  fs.mkdirSync(path.dirname(dest), { recursive: true })
  fs.writeFileSync(dest, header + body)
  index.push({ page, sha, title: (body.match(/^= (.+)$/m) || [null, page.id])[1].trim(), lines: body.split('\n').length - 1 })
  lock[page.id] = {
    source: `${page.repo}@${page.ref}`,
    commit: sha,
    path: page.path,
    dest: page.dest,
    sha256: crypto.createHash('sha256').update(header + body).digest('hex').slice(0, 16),
  }
  console.log(`${page.id.padEnd(24)} ${page.repo}@${page.ref} ${sha.slice(0, 8)} -> ${page.dest} (${body.split('\n').length - 1} lines)`)
}
fs.writeFileSync(path.join(fixturesDir, 'manifest.lock.json'), JSON.stringify(lock, null, 2) + '\n')

const rel = (d) => d.replace(/\.adoc$/, '.html')
const rows = index
  .map(({ page, sha, title, lines }) =>
    `| link:${rel(page.dest)}[${title.replace(/[|\]]/g, ' ')}]\n| ${page.repo}@${page.ref} (${sha.slice(0, 8)})\n| \`${page.path}\`${page.maxLines ? ` (trimmed to ~${page.maxLines} lines)` : ''}\n| ${lines}`
  )
  .join('\n\n')
fs.writeFileSync(
  path.join(fixturesDir, 'index.adoc'),
  '// Generated by scripts/import-fixtures.js. Do not edit by hand.\n= UI Fixtures\n:page-topic-type: reference\n\n' +
    'Real pages imported (trimmed and sanitised) from the content repos, to exercise the UI. ' +
    'Refresh with `npm run import:fixtures`; sources and trims are in `manifest.yml`.\n\n' +
    `[cols="3,3,4,1",options="header"]\n|===\n| Page | Source | Path | Lines\n\n${rows}\n|===\n`
)
